export function heroForCountry(countryCode) {
  const code = countryCode.toLowerCase();
  const key = COUNTRY_TO_HERO[code];
  if (!key) return null;
  return { key, path: HERO_IMAGES[key] };
}

export function heroByName(landmarkName) {
  const key = landmarkName.toLowerCase().replace(/\s+/g, "-");
  const path = HERO_IMAGES[key];
  if (!path) return null;
  return { key, path };
}
