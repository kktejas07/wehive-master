const I18nCtx = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem('wehive_lang') || 'en');

  useEffect(() => {
    localStorage.setItem('wehive_lang', lang);
    document.documentElement.lang = lang;
  }, [lang]);

  const t = useCallback(
    (key, fallback) => {
      const m = MESSAGES[lang] || MESSAGES.en;
      return m[key] ?? MESSAGES.en[key] ?? fallback ?? key;
    },
    [lang]
  );

  return (
    <I18nCtx.Provider value={{ lang, setLang, t, languages: LANGS }}>
      {children}
    </I18nCtx.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nCtx);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
}
